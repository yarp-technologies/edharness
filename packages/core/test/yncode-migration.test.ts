  old.query("UPDATE session SET workspace_id = 'wrk_probe'").run()
  old.query("INSERT INTO migration (id, time_completed) VALUES (?, 0)").run("20261102000000_restore_yncode_workspaces")
  old.close()
  const global = globalAt(tmp.path)
  const database = Database.layer({ path: filename }).pipe(Layer.provide(global))
